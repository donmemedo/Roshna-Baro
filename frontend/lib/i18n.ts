const FA_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];

export function localeNum(value: number | string, locale: Locale): string {
  const s = String(value);
  if (locale !== "fa") return s;
  return s.replace(/\d/g, (d) => FA_DIGITS[Number(d)]);
}

export function formatNum(value: number, locale: Locale): string {
  return localeNum(value.toLocaleString("en-US"), locale);
}

export function formatDate(iso: string | Date | null | undefined, locale: Locale): string {
  if (!iso) return "—";
  const d = typeof iso === "string" ? new Date(iso + (iso.length === 10 ? "T00:00:00" : "")) : iso;
  return new Intl.DateTimeFormat(locale === "fa" ? "fa-IR" : "en-GB", {
    day: "numeric",
    month: "long",
    ...(locale === "fa" ? { calendar: "persian" as const } : {}),
  }).format(d);
}

export function weekdayShort(d: Date, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === "fa" ? "fa-IR" : "en-GB", { weekday: "short" }).format(d);
}
